/**
 * 한글 파일명을 비교/조회용으로 정규화한다.
 *
 * macOS 파일시스템은 한글 파일명을 NFD(자모 분리)로 돌려주는데, 파일서버 cron 처럼
 * 다른 경로로 올라온 이름은 NFC(완성형)다. 눈에는 똑같아 보여도 바이트가 달라서
 * 그냥 문자열로 비교하면 이미 등록된 파일을 못 찾고 같은 자료를 한 번 더 등록한다.
 * (실제로 202512_송구영신.zip 이 NFD/NFC 로 각각 등록돼 주보가 두 건이 됐다)
 *
 * 저장값은 건드리지 않는다 — fileName 은 다운로드 표시용이고 실제 내려받기는
 * fileUrl 로 하므로, 비교하는 쪽만 맞추면 된다.
 */
export function fileKey(name) {
  return name.normalize('NFC')
}
